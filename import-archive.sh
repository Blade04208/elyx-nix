#!/usr/bin/env bash
# Import any private Elyx archive without copying it into the flake's source tree.
set -euo pipefail
if [[ $# -ne 1 ]]; then
  echo "Usage: $0 /path/to/any-name.tar.gz" >&2
  exit 1
fi
project_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
import_dir=$(mktemp -d)
trap 'rm -rf -- "$import_dir"' EXIT
# The store needs a stable internal name; the supplied file can have any name.
archive_name=elyx-private-archive.tar.gz
cp -- "$1" "$import_dir/$archive_name"
actual=$(sha256sum -- "$import_dir/$archive_name")
archive_hash=${actual%% *}
nix-store --add-fixed sha256 "$import_dir/$archive_name"
cat > "$project_dir/archive-source.nix" <<META
# Generated by import-archive.sh; contains metadata only, never the private archive.
{
  name = "$archive_name";
  sha256 = "$archive_hash";
}
META
# Include generated metadata in flakes evaluated from this Git working tree.
if git -C "$project_dir" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  git -C "$project_dir" add -N -- archive-source.nix
fi
